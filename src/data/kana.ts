const toKatakana = (items: KanaItem[]): KanaItem[] =>
  items.map((k) => ({
    ...k,
    char: k.char.replace(/[\u3041-\u3096]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60)),
  }));

